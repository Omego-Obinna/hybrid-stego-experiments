#!/usr/bin/env python3
"""
Aggregate QIM hybrid multichannel robustness / re-synchronisation simulator outputs.

Inputs
------
- run_summary.csv generated by multichannel_qim_resync_sim.py
- optional attack run_summary.csv generated with replay/tamper rates

Outputs
-------
CSV summaries, publication-ready LaTeX tables, and PDF/PNG figures:
- robustness_by_loss_ecc.csv
- latency_by_jitter_ecc.csv
- heatmap_acceptance_loss_jitter.csv
- table_resync_robustness.tex
- table_resync_latency.tex
- figure_acceptance_vs_loss.pdf/.png
- figure_resync_success_vs_loss.pdf/.png
- figure_latency_vs_jitter.pdf/.png
- figure_acceptance_heatmap.pdf/.png
- optional active_interference_summary.csv/table_active_interference.tex
- manifest.json

This script intentionally avoids detector/steganalysis metrics. It summarises protocol-level
robustness: acceptance, recovery, re-synchronisation, latency, throughput, freshness/MAC
rejections, and false accepts.
"""
from __future__ import annotations

import argparse
import json
import math
import os
from pathlib import Path
from typing import Iterable, List, Optional, Sequence

import numpy as np
import pandas as pd

import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt


REQUIRED_COLUMNS = [
    "run_id", "seed", "num_epochs", "loss_rate", "jitter_ms", "skew_ms",
    "window_W", "timeout_tau_ms", "heartbeat_h", "ecc_enabled",
    "accepted_epochs", "dropped_epochs", "recovered_epochs", "resync_events",
    "resync_success_rate", "mean_e2e_latency_ms", "p95_e2e_latency_ms",
    "throughput_epochs_per_sec", "throughput_bits_per_sec", "integrity_failure_rate",
    "acceptance_rate", "recovery_rate", "false_accepts"
]

METHOD_NOTE = (
    "This aggregation evaluates multichannel protocol robustness and re-synchronisation, "
    "not stego-object detectability. Rates are averaged over simulator runs; counts such as "
    "false accepts, replay rejections, and MAC failures are summed over the grouped runs."
)


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description="Aggregate multichannel QIM robustness simulation results into LaTeX tables and figures."
    )
    p.add_argument("--summary-csv", required=True, help="Path to main run_summary.csv from multichannel_qim_resync_sim.py")
    p.add_argument("--attack-summary-csv", default=None, help="Optional run_summary.csv from replay/tamper experiment")
    p.add_argument("--out-dir", required=True, help="Directory for CSV summaries, LaTeX tables, and figures")
    p.add_argument("--dpi", type=int, default=600, help="PNG output DPI")
    p.add_argument("--format", choices=["pdf", "png", "both"], default="both", help="Figure format")
    p.add_argument("--style", choices=["default"], default="default", help="Plot style. Kept simple for reproducibility.")
    p.add_argument("--representative-window", type=int, default=None,
                   help="Optional W filter for latency table/plots, e.g. 5. If omitted, averages over all W.")
    p.add_argument("--representative-heartbeat", type=int, default=None,
                   help="Optional heartbeat filter, e.g. 10. If omitted, averages over all h.")
    p.add_argument("--representative-skew-ms", type=float, default=None,
                   help="Optional skew filter for jitter latency plot/table, e.g. 100. If omitted, averages over all skew values.")
    p.add_argument("--exclude-attack-from-main", action="store_true", default=True,
                   help="Exclude rows with replay_rate/tamper_rate > 0 from main summaries. Enabled by default.")
    p.add_argument("--table-caption-prefix", default="QIM-style multichannel robustness",
                   help="Prefix used in generated LaTeX captions.")
    return p.parse_args()


def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def load_summary(path: Path) -> pd.DataFrame:
    if not path.exists():
        raise FileNotFoundError(f"Input CSV not found: {path}")
    df = pd.read_csv(path)
    missing = [c for c in REQUIRED_COLUMNS if c not in df.columns]
    if missing:
        raise ValueError(f"{path} is missing required columns: {missing}")
    # Normalise booleans and numerics.
    if "ecc_enabled" in df.columns:
        df["ecc_enabled"] = df["ecc_enabled"].map(_to_bool)
    for col in df.columns:
        if col not in {"run_id", "timestamp"}:
            converted = pd.to_numeric(df[col], errors="coerce")
            # Keep original values if conversion would turn every non-null entry into NaN.
            if converted.notna().any() or df[col].isna().all():
                df[col] = converted
    for optional in ["replay_rate", "tamper_rate", "burst_loss_prob", "burst_len"]:
        if optional not in df.columns:
            df[optional] = 0.0
    return df


def _to_bool(x):
    if isinstance(x, bool):
        return x
    if pd.isna(x):
        return False
    s = str(x).strip().lower()
    return s in {"true", "1", "yes", "y", "t"}


def filter_main(df: pd.DataFrame, args: argparse.Namespace) -> pd.DataFrame:
    out = df.copy()
    if args.exclude_attack_from_main:
        out = out[(out.get("replay_rate", 0) == 0) & (out.get("tamper_rate", 0) == 0)].copy()
    return out


def apply_optional_filters(df: pd.DataFrame, args: argparse.Namespace) -> pd.DataFrame:
    out = df.copy()
    if args.representative_window is not None and "window_W" in out.columns:
        out = out[out["window_W"] == args.representative_window]
    if args.representative_heartbeat is not None and "heartbeat_h" in out.columns:
        out = out[out["heartbeat_h"] == args.representative_heartbeat]
    if args.representative_skew_ms is not None and "skew_ms" in out.columns:
        out = out[np.isclose(out["skew_ms"].astype(float), args.representative_skew_ms)]
    return out


def mean_std(series: pd.Series) -> tuple[float, float, int]:
    s = pd.to_numeric(series, errors="coerce").dropna()
    if len(s) == 0:
        return float("nan"), float("nan"), 0
    return float(s.mean()), float(s.std(ddof=1)) if len(s) > 1 else 0.0, int(len(s))


def agg_mean_std(df: pd.DataFrame, group_cols: Sequence[str], metrics: Sequence[str]) -> pd.DataFrame:
    records = []
    grouped = df.groupby(list(group_cols), dropna=False, sort=True)
    for key, g in grouped:
        if not isinstance(key, tuple):
            key = (key,)
        rec = {c: v for c, v in zip(group_cols, key)}
        rec["n_runs"] = int(len(g))
        rec["n_seeds"] = int(g["seed"].nunique()) if "seed" in g.columns else int(len(g))
        for m in metrics:
            if m in g.columns:
                mu, sd, n = mean_std(g[m])
                rec[f"{m}_mean"] = mu
                rec[f"{m}_std"] = sd
                rec[f"{m}_n"] = n
        # useful count totals where present
        for c in ["false_accepts", "mac_failures", "replay_rejections", "stale_epoch_rejections",
                  "nonce_freshness_rejections", "out_of_window_rejections", "resync_events",
                  "recovered_epochs", "accepted_epochs", "dropped_epochs"]:
            if c in g.columns:
                rec[f"{c}_sum"] = int(pd.to_numeric(g[c], errors="coerce").fillna(0).sum())
        records.append(rec)
    return pd.DataFrame(records)


def fmt_rate(x: float, sd: Optional[float] = None, digits: int = 2) -> str:
    if x is None or pd.isna(x):
        return "--"
    if sd is None or pd.isna(sd):
        return f"{100.0*x:.{digits}f}"
    return f"${100.0*x:.{digits}f} \\pm {100.0*sd:.{digits}f}$"


def fmt_num(x: float, sd: Optional[float] = None, digits: int = 2) -> str:
    if x is None or pd.isna(x):
        return "--"
    if sd is None or pd.isna(sd):
        return f"{x:.{digits}f}"
    return f"${x:.{digits}f} \\pm {sd:.{digits}f}$"


def fmt_int(x) -> str:
    if x is None or pd.isna(x):
        return "--"
    return f"{int(round(float(x)))}"


def bool_label(x) -> str:
    return "on" if bool(x) else "off"


def write_latex_table_robustness(df: pd.DataFrame, path: Path, caption_prefix: str) -> None:
    lines = []
    lines.append(r"\begin{table*}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{" + caption_prefix + r": acceptance, recovery and re-synchronisation under channel loss. Rates are mean~$\pm$~standard deviation over simulator runs.}")
    lines.append(r"\label{tab:qim_resync_robustness}")
    lines.append(r"\resizebox{\textwidth}{!}{%")
    lines.append(r"\begin{tabular}{llcccccc}")
    lines.append(r"\toprule")
    lines.append(r"Loss $r$ & ECC & Runs & Acceptance (\%) & Recovery (\%) & Re-sync Success (\%) & Integrity Fail. (\%) & False Accepts \\")
    lines.append(r"\midrule")
    for _, row in df.iterrows():
        loss = fmt_rate(row.get("loss_rate"), None, 0)
        ecc = bool_label(row.get("ecc_enabled"))
        runs = fmt_int(row.get("n_runs"))
        acc = fmt_rate(row.get("acceptance_rate_mean"), row.get("acceptance_rate_std"), 2)
        rec = fmt_rate(row.get("recovery_rate_mean"), row.get("recovery_rate_std"), 2)
        rs = fmt_rate(row.get("resync_success_rate_mean"), row.get("resync_success_rate_std"), 2)
        integ = fmt_rate(row.get("integrity_failure_rate_mean"), row.get("integrity_failure_rate_std"), 4)
        false = fmt_int(row.get("false_accepts_sum"))
        lines.append(f"{loss} & {ecc} & {runs} & {acc} & {rec} & {rs} & {integ} & {false} \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}%")
    lines.append(r"}")
    lines.append(r"\end{table*}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_latex_table_latency(df: pd.DataFrame, path: Path, caption_prefix: str) -> None:
    lines = []
    lines.append(r"\begin{table*}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{" + caption_prefix + r": latency and throughput under jitter. Values are mean~$\pm$~standard deviation over simulator runs.}")
    lines.append(r"\label{tab:qim_resync_latency}")
    lines.append(r"\resizebox{\textwidth}{!}{%")
    lines.append(r"\begin{tabular}{llccccc}")
    lines.append(r"\toprule")
    lines.append(r"Jitter (ms) & ECC & Runs & Mean Latency (ms) & P95 Latency (ms) & Mean Re-sync Delay (ms) & Throughput (epochs/s) \\")
    lines.append(r"\midrule")
    for _, row in df.iterrows():
        jitter = fmt_num(row.get("jitter_ms"), None, 0)
        ecc = bool_label(row.get("ecc_enabled"))
        runs = fmt_int(row.get("n_runs"))
        mean_lat = fmt_num(row.get("mean_e2e_latency_ms_mean"), row.get("mean_e2e_latency_ms_std"), 2)
        p95_lat = fmt_num(row.get("p95_e2e_latency_ms_mean"), row.get("p95_e2e_latency_ms_std"), 2)
        mean_resync = fmt_num(row.get("mean_resync_delay_ms_mean"), row.get("mean_resync_delay_ms_std"), 2)
        thr = fmt_num(row.get("throughput_epochs_per_sec_mean"), row.get("throughput_epochs_per_sec_std"), 2)
        lines.append(f"{jitter} & {ecc} & {runs} & {mean_lat} & {p95_lat} & {mean_resync} & {thr} \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}%")
    lines.append(r"}")
    lines.append(r"\end{table*}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def write_latex_table_attack(df: pd.DataFrame, path: Path, caption_prefix: str) -> None:
    lines = []
    lines.append(r"\begin{table}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{" + caption_prefix + r": active replay/tamper rejection results. Counts are summed over grouped runs.}")
    lines.append(r"\label{tab:qim_resync_attack}")
    lines.append(r"\resizebox{\linewidth}{!}{%")
    lines.append(r"\begin{tabular}{llllrrrr}")
    lines.append(r"\toprule")
    lines.append(r"Loss & Replay & Tamper & ECC & MAC Failures & Replay Reject. & Stale Reject. & False Accepts \\")
    lines.append(r"\midrule")
    for _, row in df.iterrows():
        loss = fmt_rate(row.get("loss_rate"), None, 0)
        replay = fmt_rate(row.get("replay_rate"), None, 2)
        tamper = fmt_rate(row.get("tamper_rate"), None, 2)
        ecc = bool_label(row.get("ecc_enabled"))
        mac = fmt_int(row.get("mac_failures_sum"))
        rep = fmt_int(row.get("replay_rejections_sum"))
        stale = fmt_int(row.get("stale_epoch_rejections_sum"))
        false = fmt_int(row.get("false_accepts_sum"))
        lines.append(f"{loss} & {replay} & {tamper} & {ecc} & {mac} & {rep} & {stale} & {false} \\")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}%")
    lines.append(r"}")
    lines.append(r"\end{table}")
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")


def save_fig(fig: plt.Figure, out_base: Path, fmt: str, dpi: int) -> None:
    if fmt in {"pdf", "both"}:
        fig.savefig(str(out_base.with_suffix(".pdf")), bbox_inches="tight")
    if fmt in {"png", "both"}:
        fig.savefig(str(out_base.with_suffix(".png")), dpi=dpi, bbox_inches="tight")
    plt.close(fig)


def plot_line_by_ecc(df: pd.DataFrame, x_col: str, y_col: str, y_label: str, out_base: Path,
                     fmt: str, dpi: int, percent_y: bool = True) -> None:
    fig, ax = plt.subplots(figsize=(6.5, 4.1))
    for ecc_value, group in df.groupby("ecc_enabled", sort=True):
        group = group.sort_values(x_col)
        x = group[x_col].astype(float).to_numpy()
        y = group[f"{y_col}_mean"].astype(float).to_numpy()
        sd = group[f"{y_col}_std"].astype(float).fillna(0).to_numpy()
        if percent_y:
            y_plot = y * 100.0
            yerr = sd * 100.0
        else:
            y_plot = y
            yerr = sd
        label = f"ECC {bool_label(ecc_value)}"
        ax.errorbar(x, y_plot, yerr=yerr, marker="o", linewidth=1.8, capsize=3, label=label)
    ax.set_xlabel("Loss rate")
    ax.set_ylabel(y_label)
    ax.grid(True, linewidth=0.4, alpha=0.4)
    ax.legend(frameon=False)
    save_fig(fig, out_base, fmt, dpi)


def plot_latency_vs_jitter(df: pd.DataFrame, out_base: Path, fmt: str, dpi: int) -> None:
    fig, ax = plt.subplots(figsize=(6.5, 4.1))
    for ecc_value, group in df.groupby("ecc_enabled", sort=True):
        group = group.sort_values("jitter_ms")
        x = group["jitter_ms"].astype(float).to_numpy()
        y = group["p95_e2e_latency_ms_mean"].astype(float).to_numpy()
        sd = group["p95_e2e_latency_ms_std"].astype(float).fillna(0).to_numpy()
        ax.errorbar(x, y, yerr=sd, marker="o", linewidth=1.8, capsize=3, label=f"ECC {bool_label(ecc_value)}")
    ax.set_xlabel("Jitter (ms)")
    ax.set_ylabel("P95 end-to-end latency (ms)")
    ax.grid(True, linewidth=0.4, alpha=0.4)
    ax.legend(frameon=False)
    save_fig(fig, out_base, fmt, dpi)


def plot_heatmap(df: pd.DataFrame, out_base: Path, fmt: str, dpi: int) -> None:
    # Use mean acceptance over all ECC/window/heartbeat unless caller filtered beforehand.
    piv = df.groupby(["loss_rate", "jitter_ms"], sort=True)["acceptance_rate"].mean().reset_index()
    table = piv.pivot(index="loss_rate", columns="jitter_ms", values="acceptance_rate").sort_index().sort_index(axis=1)
    z = table.to_numpy() * 100.0
    fig, ax = plt.subplots(figsize=(6.2, 4.2))
    im = ax.imshow(z, aspect="auto")
    ax.set_xticks(np.arange(len(table.columns)))
    ax.set_yticks(np.arange(len(table.index)))
    ax.set_xticklabels([f"{float(c):.0f}" for c in table.columns])
    ax.set_yticklabels([f"{100.0*float(r):.0f}" for r in table.index])
    ax.set_xlabel("Jitter (ms)")
    ax.set_ylabel("Loss rate (%)")
    cbar = fig.colorbar(im, ax=ax)
    cbar.set_label("Mean acceptance rate (%)")
    for i in range(z.shape[0]):
        for j in range(z.shape[1]):
            val = z[i, j]
            if np.isfinite(val):
                ax.text(j, i, f"{val:.1f}", ha="center", va="center", fontsize=8)
    save_fig(fig, out_base, fmt, dpi)


def main() -> None:
    args = parse_args()
    out_dir = Path(args.out_dir)
    ensure_dir(out_dir)

    summary_path = Path(args.summary_csv)
    df0 = load_summary(summary_path)
    df = filter_main(df0, args)
    if df.empty:
        raise ValueError("No rows available after filtering main summary. Check replay/tamper filters or input CSV.")

    # Main robustness by loss and ECC.
    robustness_metrics = ["acceptance_rate", "recovery_rate", "resync_success_rate", "integrity_failure_rate"]
    robust = agg_mean_std(df, ["loss_rate", "ecc_enabled"], robustness_metrics)
    robust = robust.sort_values(["loss_rate", "ecc_enabled"])
    robust.to_csv(out_dir / "robustness_by_loss_ecc.csv", index=False)
    write_latex_table_robustness(robust, out_dir / "table_resync_robustness.tex", args.table_caption_prefix)

    # Latency table can use optional filters to avoid over-averaging if user asks for representative setup.
    lat_df = apply_optional_filters(df, args)
    if lat_df.empty:
        raise ValueError("No rows available for latency table after optional filters. Remove/adjust representative filters.")
    latency_metrics = [
        "mean_e2e_latency_ms", "median_e2e_latency_ms", "p95_e2e_latency_ms",
        "mean_resync_delay_ms", "p95_resync_delay_ms", "throughput_epochs_per_sec"
    ]
    latency = agg_mean_std(lat_df, ["jitter_ms", "ecc_enabled"], latency_metrics)
    latency = latency.sort_values(["jitter_ms", "ecc_enabled"])
    latency.to_csv(out_dir / "latency_by_jitter_ecc.csv", index=False)
    write_latex_table_latency(latency, out_dir / "table_resync_latency.tex", args.table_caption_prefix)

    # Heatmap data.
    heat = df.groupby(["loss_rate", "jitter_ms"], sort=True).agg(
        acceptance_rate_mean=("acceptance_rate", "mean"),
        recovery_rate_mean=("recovery_rate", "mean"),
        resync_success_rate_mean=("resync_success_rate", "mean"),
        p95_e2e_latency_ms_mean=("p95_e2e_latency_ms", "mean"),
        n_runs=("run_id", "count"),
    ).reset_index()
    heat.to_csv(out_dir / "heatmap_acceptance_loss_jitter.csv", index=False)

    # Figures.
    plot_line_by_ecc(robust, "loss_rate", "acceptance_rate", "Mean acceptance rate (%)",
                     out_dir / "figure_acceptance_vs_loss", args.format, args.dpi, percent_y=True)
    plot_line_by_ecc(robust, "loss_rate", "resync_success_rate", "Mean re-sync success rate (%)",
                     out_dir / "figure_resync_success_vs_loss", args.format, args.dpi, percent_y=True)
    plot_latency_vs_jitter(latency, out_dir / "figure_latency_vs_jitter", args.format, args.dpi)
    plot_heatmap(df, out_dir / "figure_acceptance_heatmap", args.format, args.dpi)

    outputs = {
        "summary_csv": str(summary_path),
        "n_input_rows": int(len(df0)),
        "n_main_rows_after_filter": int(len(df)),
        "note": METHOD_NOTE,
        "optional_filters": {
            "representative_window": args.representative_window,
            "representative_heartbeat": args.representative_heartbeat,
            "representative_skew_ms": args.representative_skew_ms,
        },
        "generated": [
            "robustness_by_loss_ecc.csv",
            "latency_by_jitter_ecc.csv",
            "heatmap_acceptance_loss_jitter.csv",
            "table_resync_robustness.tex",
            "table_resync_latency.tex",
            f"figure_acceptance_vs_loss.{args.format if args.format != 'both' else 'pdf/png'}",
            f"figure_resync_success_vs_loss.{args.format if args.format != 'both' else 'pdf/png'}",
            f"figure_latency_vs_jitter.{args.format if args.format != 'both' else 'pdf/png'}",
            f"figure_acceptance_heatmap.{args.format if args.format != 'both' else 'pdf/png'}",
        ]
    }

    # Optional attack summary.
    if args.attack_summary_csv:
        attack_path = Path(args.attack_summary_csv)
        adf = load_summary(attack_path)
        # Keep only rows with active interference if possible; otherwise summarise all.
        if "replay_rate" in adf.columns and "tamper_rate" in adf.columns:
            active = adf[(pd.to_numeric(adf["replay_rate"], errors="coerce").fillna(0) > 0) |
                         (pd.to_numeric(adf["tamper_rate"], errors="coerce").fillna(0) > 0)].copy()
            if active.empty:
                active = adf.copy()
        else:
            active = adf.copy()
        attack_metrics = ["acceptance_rate", "integrity_failure_rate"]
        attack = agg_mean_std(active, ["loss_rate", "replay_rate", "tamper_rate", "ecc_enabled"], attack_metrics)
        attack = attack.sort_values(["loss_rate", "replay_rate", "tamper_rate", "ecc_enabled"])
        attack.to_csv(out_dir / "active_interference_summary.csv", index=False)
        write_latex_table_attack(attack, out_dir / "table_active_interference.tex", args.table_caption_prefix)
        outputs["attack_summary_csv"] = str(attack_path)
        outputs["n_attack_rows"] = int(len(active))
        outputs["generated"].extend(["active_interference_summary.csv", "table_active_interference.tex"])

    with open(out_dir / "aggregation_manifest.json", "w", encoding="utf-8") as f:
        json.dump(outputs, f, indent=2)

    print(f"[OK] Aggregation complete: {out_dir}")
    for name in outputs["generated"]:
        print(f"  - {name}")


if __name__ == "__main__":
    main()
